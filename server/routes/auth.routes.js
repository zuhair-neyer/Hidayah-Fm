const router=require('express').Router();
const ctrl=require('../controllers/auth.controller');
const {requireAuth}=require('../middleware/auth');
const wrap=require('../utils/async');
router.post('/signup',wrap(ctrl.signup));
router.post('/login',wrap(ctrl.login));
router.post('/refresh',wrap(ctrl.refresh));
router.post('/reset-password',wrap(ctrl.resetPassword));
router.post('/reset-password/verify',wrap(ctrl.verifyPasswordReset));
router.post('/reset-password/confirm',wrap(ctrl.confirmPasswordReset));
router.get('/me',requireAuth,wrap(ctrl.me));
router.patch('/me',requireAuth,wrap(ctrl.update));
router.delete('/me',requireAuth,wrap(ctrl.remove));
router.post('/change-password',requireAuth,wrap(ctrl.password));
router.get('/settings',requireAuth,wrap(ctrl.settings));
router.put('/settings',requireAuth,wrap(ctrl.saveSettings));
router.get('/export',requireAuth,wrap(ctrl.exportData));
router.get('/state',requireAuth,wrap(ctrl.state));
router.put('/bookmark',requireAuth,wrap(ctrl.bookmark));
router.put('/playback',requireAuth,wrap(ctrl.playback));
module.exports=router;
